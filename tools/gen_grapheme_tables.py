#!/usr/bin/env python3
"""Generate src/nllb-grapheme-data.h - UAX#29 Grapheme_Cluster_Break tables.

Why this exists at all: HuggingFace's `spm_precompiled` iterates the input in
GRAPHEME CLUSTERS, not codepoints, and a cluster shorter than 6 bytes that hits
the charsmap trie is replaced WHOLE - so "\\r\\n" becomes one space, and
"A U+0302 U+0300" becomes "A-circumflex" with the second mark dropped. Getting
the cluster boundaries wrong changes the ids. See claude/step8-cpp-tokenizer.md.

    pip install regex
    python tools/gen_grapheme_tables.py > src/nllb-grapheme-data.h

The generated header is COMMITTED, so building nllb.cpp needs no Python. Re-run
this only to move to a newer Unicode version, and re-run the tokenizer gate
afterwards: the two implementations must agree on the same UCD.
"""
from __future__ import annotations

import sys

try:
    import regex
except ImportError:                     # importable without regex, so callers
    regex = None                        # can degrade rather than die on import

# Order matters only for the report; every codepoint has exactly one GCB value.
PROPS = [
    ("CR", "NLLB_GCB_CR"),
    ("LF", "NLLB_GCB_LF"),
    ("Control", "NLLB_GCB_CONTROL"),
    ("Extend", "NLLB_GCB_EXTEND"),
    ("ZWJ", "NLLB_GCB_ZWJ"),
    ("Regional_Indicator", "NLLB_GCB_RI"),
    ("Prepend", "NLLB_GCB_PREPEND"),
    ("SpacingMark", "NLLB_GCB_SPACINGMARK"),
    ("L", "NLLB_GCB_L"),
    ("V", "NLLB_GCB_V"),
    ("T", "NLLB_GCB_T"),
]
# LV and LVT are deliberately NOT tabulated: they are exactly the Hangul
# syllable block U+AC00..U+D7A3, LV when (c - 0xAC00) % 28 == 0 and LVT
# otherwise. Two lines of arithmetic against 798 table rows.
HANGUL_LO, HANGUL_HI = 0xAC00, 0xD7A3


def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        hit = False if 0xD800 <= c < 0xE000 else pred(c)
        if hit and start is None:
            start = c
        elif not hit and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


# The numeric values of the nllb_gcb enum, in the order it declares them.
# These are what go INTO THE GGUF, so they are part of the file format: do not
# renumber them without bumping something the loader checks.
ENUM_VALUE = {enum: i + 1 for i, (_, enum) in enumerate(PROPS)}
ENUM_VALUE["NLLB_GCB_LV"] = len(PROPS) + 1
ENUM_VALUE["NLLB_GCB_LVT"] = len(PROPS) + 2


def build_tables():
    """(gcb_rows, extpict_rows, ucd_version).

    Importable, because tools/convert_nllb_to_gguf.py bakes these same tables
    into the GGUF and there must be exactly one place they are computed. The
    committed header and the file's copy are the same numbers by construction.
    """
    if regex is None:
        raise ImportError("the `regex` package is required: pip install regex")
    rows = []
    for name, enum in PROPS:
        pat = regex.compile(r"\p{gcb=%s}" % name)
        rs = ranges(lambda c: bool(pat.fullmatch(chr(c))))
        if name in ("L", "V", "T"):
            rs = [(a, b) for a, b in rs if not (HANGUL_LO <= a <= HANGUL_HI)]
        rows += [(a, b, enum) for a, b in rs]
    rows.sort()

    pict = regex.compile(r"\p{Extended_Pictographic}")
    pr = ranges(lambda c: bool(pict.fullmatch(chr(c))))
    return rows, pr, regex.__version__


def flatten(rows, pr):
    """The GGUF form: gcb as (lo, hi, prop) triples, extpict as (lo, hi) pairs."""
    gcb = []
    for a, b, enum in rows:
        gcb += [a, b, ENUM_VALUE[enum]]
    ext = []
    for a, b in pr:
        ext += [a, b]
    return gcb, ext


def main() -> None:
    rows, pr, _ = build_tables()

    w = sys.stdout.write
    w("// GENERATED by tools/gen_grapheme_tables.py - do not edit by hand.\n")
    w("// Unicode data from the `regex` package, UCD %s.\n" % regex.__version__)
    w("//\n// UAX#29 Grapheme_Cluster_Break, minus LV/LVT which are computed\n"
      "// arithmetically from the Hangul syllable block.\n")
    w("#pragma once\n#include <cstdint>\n\n")
    w("enum nllb_gcb {\n    NLLB_GCB_OTHER = 0,\n")
    for _, enum in PROPS:
        w("    %s,\n" % enum)
    w("    NLLB_GCB_LV,\n    NLLB_GCB_LVT,\n};\n\n")
    w("struct nllb_gcb_range { uint32_t lo, hi; uint8_t prop; };\n\n")
    w("static const nllb_gcb_range NLLB_GCB_TABLE[] = {\n")
    for a, b, e in rows:
        w("    {0x%04X, 0x%04X, %s},\n" % (a, b, e))
    w("};\n")
    w("static const int NLLB_GCB_TABLE_N = %d;\n\n" % len(rows))
    w("struct nllb_cp_range { uint32_t lo, hi; };\n\n")
    w("// Extended_Pictographic, for GB11 (emoji ZWJ sequences).\n")
    w("static const nllb_cp_range NLLB_EXTPICT_TABLE[] = {\n")
    for a, b in pr:
        w("    {0x%04X, 0x%04X},\n" % (a, b))
    w("};\n")
    w("static const int NLLB_EXTPICT_TABLE_N = %d;\n" % len(pr))
    print("// %d gcb ranges, %d extpict ranges" % (len(rows), len(pr)),
          file=sys.stderr)


if __name__ == "__main__":
    main()
